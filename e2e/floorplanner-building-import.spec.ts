  await dialog.getByRole('button', { name: 'Apply scale', exact: true }).click()
  await dialog.getByRole('button', { name: 'Set scale', exact: true }).click()
  await svg.click({ position: { x: box.width * .125, y: box.height / 6 } })
  await svg.click({ position: { x: box.width * .125, y: box.height / 2 } })
  await dialog.getByLabel('Known distance for recovery.png').fill('20')
  await dialog.getByRole('button', { name: 'Verify second distance' }).click()
  await expect(dialog.getByText(/Scale check passed/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Room boundary', exact: true }).click()
  await dialog.getByRole('button', { name: 'Build rooms from connected walls' }).click()
