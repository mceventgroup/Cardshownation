  const base64 = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 800; c.height = 600
    const ctx = c.getContext('2d')!; ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 800, 600)
    ctx.strokeStyle = '#111'; ctx.lineWidth = 6; ctx.strokeRect(20, 20, 750, 550)
    ctx.fillStyle = '#111'; ctx.fillRect(380, 270, 18, 18)
    ctx.lineWidth = 2; for (let i = 0; i < 6; i++) ctx.strokeRect(70 + i * 110, 150, 65, 27)
    return c.toDataURL('image/png').split(',')[1]
  })
