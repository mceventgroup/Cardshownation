test('restricting detection to the room excludes the sheet border and supports undo', async ({ page }) => {
  await open(page)
  const base64 = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 800; c.height = 600
    const ctx = c.getContext('2d')!; ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 800, 600)
    ctx.strokeStyle = '#111'; ctx.lineWidth = 4; ctx.strokeRect(5, 5, 790, 590); ctx.strokeRect(100, 100, 600, 400)
    return c.toDataURL('image/png').split(',')[1]
  })
  await page.getByLabel('Floor plan drawing files').setInputFiles({ name: 'border.png', mimeType: 'image/png', buffer: Buffer.from(base64, 'base64') })
  const dialog = page.getByRole('dialog', { name: 'Import & trace building' })
  await expect(dialog.getByText(/8 walls/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Detection area', exact: true }).click()
  const svg = dialog.getByLabel('Review building on border.png')
  await svg.scrollIntoViewIfNeeded()
  const box = (await svg.boundingBox())!
  // Keep the gesture in the visible viewport; select the upper half of the room.
  await page.mouse.move(box.x + box.width * .1, box.y + box.height * .1)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .9, box.y + box.height * .45, { steps: 5 })
  await page.mouse.up()
  await expect(dialog.getByRole('button', { name: 'Use whole page' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Detect walls & pillars again' }).click()
  await expect(dialog.getByText(/3 walls/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Undo review change' }).click()
  await expect(dialog.getByText(/8 walls/)).toBeVisible()
})

test('PDF dimension labels are selectable and every page needs its own scale', async ({ page }) => {
  await open(page)
  const { jsPDF } = await import('jspdf')
  const pdf = new jsPDF({ unit: 'pt', format: [600, 400], orientation: 'landscape' })
  pdf.setLineWidth(4); pdf.rect(30, 50, 500, 280); pdf.text(`40'-0"`, 180, 35)
  pdf.addPage([600, 400], 'landscape'); pdf.rect(30, 50, 500, 280); pdf.text('12 m', 180, 35)
  await page.getByLabel('Floor plan drawing files').setInputFiles({ name: 'halls.pdf', mimeType: 'application/pdf', buffer: Buffer.from(pdf.output('arraybuffer')) })
  const dialog = page.getByRole('dialog', { name: 'Import & trace building' })
  const label = dialog.getByLabel('Dimension label for halls.pdf - page 1')
  await expect(label).toBeVisible()
  await label.selectOption(`40'-0"`)
  await expect(dialog.getByLabel('Known distance for halls.pdf - page 1')).toHaveValue('480')
  await expect(dialog.getByLabel('Distance unit for halls.pdf - page 1')).toHaveValue('in')
  await dialog.getByRole('button', { name: /Page 2 halls/ }).click()
  await expect(dialog.getByLabel('Dimension label for halls.pdf - page 2')).toBeVisible()
  await dialog.getByRole('checkbox', { name: 'I checked the walls, pillars, and scale.' }).check()
  await expect(dialog.getByRole('button', { name: 'Import scaled building' })).toBeDisabled()
  await page.screenshot({ path: 'test-results/building-import-pdf.png' })
})

