  await expect(dialog.getByRole('button', { name: 'Import scaled building' })).toBeDisabled()
  const svg = dialog.getByLabel('Review building on venue.png')
  await svg.scrollIntoViewIfNeeded()
  const box = (await svg.boundingBox())!
  await svg.click({ position: { x: box.width * .125, y: box.height / 6 } })
  await svg.click({ position: { x: box.width * .625, y: box.height / 6 } })
